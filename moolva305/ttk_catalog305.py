def cards_list(query="", category="", start=0, limit=60):
    if not isinstance(query,str) or len(query)>120:
        raise ValueError("Проверьте поисковую строку")
    if not isinstance(category,str) or len(category)>100:
        raise ValueError("Некорректная категория")
    try:start,limit=int(start),int(limit)
    except (TypeError,ValueError) as exc:raise ValueError("Некорректная страница") from exc
    if not 0<=start<=5000 or not 1<=limit<=100:
        raise ValueError("Недопустимое число блюд на странице")
    words=query.casefold().strip()
    found=[x for x in catalog() if
          (not words or words in x["title"].casefold()) and
          (not category or category==x["category"])]
    return {"total":len(found),"catalog_size":len(catalog()),
            "categories":sorted({x["category"] for x in catalog()}),
            "items":[{"code":x["catalog_code"],"title":x["title"],
                      "category":x["category"],"kind":x["kind"],
                      "draft":True}
                     for x in found[start:start+limit]],
            "warning":"Проектные рецептуры для проработки: не утверждены и не являются нормативным сборником."}


def by_code(code):
    if not isinstance(code,str) or len(code)>32:
        raise ValueError("Некорректный код рецептуры")
    entry=next((x for x in catalog() if x["catalog_code"]==code),None)
    if entry is None:raise ValueError("Блюдо отсутствует в проектном каталоге")
    # Deep copy; a user cannot mutate catalog seed between requests.
    import copy
    return copy.deepcopy(entry)
